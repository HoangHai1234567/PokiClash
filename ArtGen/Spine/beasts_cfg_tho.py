def _fx(hid, extra):
    """bộ hiệu ứng đất đá mặc định thay bộ NƯỚC của beast.py: vòng sỏi bụi dưới chân, lốc bụi tụ lực / tiến hóa (chỉ vòng sau),
    sóng đất đá cuối chiêu, sỏi; extra là ảnh riêng của dòng (tên không có tiền tố tho_chung thì thêm <hid>_)."""
