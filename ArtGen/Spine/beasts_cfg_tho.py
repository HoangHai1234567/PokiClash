def _tam_thoi():
    import os
    d = os.path.join(os.path.dirname(os.path.abspath(__file__)), "inbox", "fx")
    chung = "tho_chung" if os.path.isfile(os.path.join(d, "tho_chung_ring.png")) else "kim_chung"

    def fix(fx):
        for slot, v in list(fx.items()):
            if v[0] and not os.path.isfile(os.path.join(d, v[0] + ".png")):
                suf, flag = _TAM.get(slot, ("_spark", None))
                fx[slot] = (chung + suf, v[1], flag if flag is not None else v[2])

    for c in THO.values():
        fix(c["fx"])
        for f in c.get("fx_form", {}).values():
            fix(f)


